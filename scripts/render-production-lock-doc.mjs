#!/usr/bin/env node
/**
 * scripts/render-production-lock-doc.mjs
 *
 * Deterministically renders docs/HAY_DEP_PRODUCTION_LOCK.md from docs/HAY_DEP_PRODUCTION_LOCK.json (SSOT).
 *
 * Usage:
 *   node scripts/render-production-lock-doc.mjs
 *   node scripts/render-production-lock-doc.mjs --check
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'docs', 'HAY_DEP_PRODUCTION_LOCK.json');
const MD_PATH = path.join(ROOT, 'docs', 'HAY_DEP_PRODUCTION_LOCK.md');

export function renderProductionLockMarkdown(lock) {
  const qaDims = (lock.perImageQa?.requiredDimensions || []).map((dim, i) => `${i + 1}. **\`${dim}\`**`).join('\n');
  const exclusions = (lock.hardExclusions || []).join(', ');
  const bgColors = (lock.imageStyle?.palette?.background || []).join(' / ');
  const clothingColors = (lock.imageStyle?.palette?.clothing || []).join(' / ');
  const accents = (lock.imageStyle?.palette?.accents || []).join(' / ');
  const allowedMotion = (lock.motionGrammar?.allowed || []).join(', ');
  const forbiddenMotion = (lock.motionGrammar?.forbidden || []).join(', ');
  const audioModes = (lock.audioContract?.modes || []).join(', ');
  const verifiedVideos = (lock.evidence?.verifiedVideos || []).join(', ');

  const lines = [
    '# HAY & ĐẸP. — Production Baseline Lock (SSOT Mirror)',
    '',
    '> **Notice:** This document is auto-generated from \`docs/HAY_DEP_PRODUCTION_LOCK.json\` via \`scripts/render-production-lock-doc.mjs\`.',
    '> Do not edit this file directly. Edit the JSON SSOT and re-run the generator.',
    '',
    `**Status:** \`${lock.status}\`  `,
    `**Lock Date:** ${lock.lockDate}  `,
    `**Baseline Version:** ${lock.version}  `,
    `**Template ID:** \`${lock.templateId}\`  `,
    '**Applicability:** All current and future HAY & ĐẸP. automated pipeline and template generation tasks.',
    '',
    '---',
    '',
    '## 1. Image Model Exclusivity',
    '',
    '```text',
    `${lock.imageModel?.modelId} ONLY`,
    '```',
    '',
    '- **Policy:** Never switch the image model without an explicit new human decision and sign-off.',
    `- **Provider:** Cloudflare Workers AI (\`${lock.imageModel?.provider}\`).`,
    `- **Policy Flag:** \`${lock.imageModel?.policy}\` (\`allowModelSwitch: ${lock.imageModel?.allowModelSwitch}\`).`,
    `- **Hard Visual Exclusions:** ${exclusions}.`,
    '',
    '---',
    '',
    '## 2. Image Style & Palette',
    '',
    `- **Genre:** ${lock.imageStyle?.genre}`,
    `- **Photorealism:** ${lock.imageStyle?.photorealism ? 'Allowed' : 'STRICTLY FORBIDDEN'}`,
    '- **Palette Contract:**',
    `  - Background: ${bgColors}`,
    `  - Clothing: ${clothingColors}`,
    `  - Wood: ${lock.imageStyle?.palette?.wood}`,
    `  - Linework: ${lock.imageStyle?.palette?.linework}`,
    `  - Accents: ${accents}`,
    '',
    '---',
    '',
    '## 3. Character Identity Contract',
    '',
    '```text',
    'Cross-shot character identity consistency is NOT required.',
    '```',
    '',
    '- **Contract Rule:** Each image is evaluated independently on its own visual and narrative merits.',
    '- **Zero Attempt Waste:** Do NOT consume retry attempts attempting to force cross-shot character facial or biometric likeness.',
    '- **Allowed Semantics:** Role labels, people count, family-role semantics, and world hints are permitted.',
    '',
    '---',
    '',
    '## 4. Per-Image Visual QA Dimensions',
    '',
    `Every individual image asset must independently pass all ${lock.perImageQa?.requiredDimensions?.length} criteria:`,
    '',
    qaDims,
    '',
    '> **Production Principle:** Machine integrity (valid JPEG headers, file size >= 30KB) MUST NEVER automatically imply visual PASS. All five visual QA dimensions must explicitly PASS.',
    `> **NO FAKE PASS:** ${lock.perImageQa?.noFakePass ? 'Enforced' : 'Disabled'}.`,
    '',
    '---',
    '',
    '## 5. Retry & Asset Cleanup Policy',
    '',
    '```text',
    `maximum ${lock.retryPolicy?.maxRealAttempts} real generated attempts per asset`,
    'HTTP 429 does not consume a visual attempt',
    `HTTP 429 => ${lock.retryPolicy?.http429Action}`,
    'no account rotation',
    `no model switching (${lock.retryPolicy?.allowModelSwitch ? 'allowed' : 'forbidden'})`,
    '```',
    '',
    '- **Quota Pausing:** If Cloudflare returns \`HTTP 429\`, mark \`PAUSED_QUOTA\` immediately.',
    `- **Generation Cap:** At most ${lock.retryPolicy?.maxRealAttempts} generative attempts per shot.`,
    `- **Deterministic Raster Cleanup:** Permitted only after ${lock.retryPolicy?.deterministicRasterCleanupAllowedAfterAttempts} attempts. Cleaned assets return to pending review.`,
    '',
    '---',
    '',
    '## 6. Duration & Voice Contract',
    '',
    `- **Allowed Duration:** ${lock.durationContract?.allowedSeconds?.[0]}–${lock.durationContract?.allowedSeconds?.[1]} seconds`,
    `- **Preferred Duration:** ${lock.durationContract?.preferredSeconds?.[0]}–${lock.durationContract?.preferredSeconds?.[1]} seconds`,
    `- **Canonical Voice:** Narration text is canonical; rewrite is strictly forbidden (\`rewriteForbidden: ${lock.durationContract?.rewriteForbidden}\`).`,
    '',
    '---',
    '',
    '## 7. Framing & Scene Composition',
    '',
    `- **Square Asset Preset:** \`${lock.framing?.cleanSquareAssetsComposition}\``,
    `- **Default Geometry:** Width ${lock.framing?.defaultDimensions?.width}px, Height ${lock.framing?.defaultDimensions?.height}px, Radius ${lock.framing?.defaultDimensions?.radius}px, Top ${lock.framing?.defaultDimensions?.top}px, Left ${lock.framing?.defaultDimensions?.left}px.`,
    `- **Prohibit Asymmetric Presets for Square Assets:** ${lock.framing?.prohibitAsymmetricForSquare ? 'Enforced' : 'Disabled'}.`,
    '',
    '---',
    '',
    '## 8. Motion Grammar',
    '',
    `Lock the accepted ${lock.motionGrammar?.version} deterministic calm motion grammar:`,
    '',
    `- **Allowed Profiles:** ${allowedMotion}`,
    `- **Hard Cuts:** ${lock.motionGrammar?.hardCuts ? 'Enforced (0-frame transition fade)' : 'Disabled'}`,
    `- **Vertical Motion:** translateY = ${lock.motionGrammar?.translateY}px`,
    `- **Forbidden:** ${forbiddenMotion}`,
    '',
    '---',
    '',
    '## 9. Brand Watermark',
    '',
    `- **Asset Path:** \`${lock.brandWatermark?.assetPath}\``,
    '- **Positioning:**',
    `  - Position: ${lock.brandWatermark?.position}`,
    `  - Inset Top: ${lock.brandWatermark?.insetTop}px (min: ${lock.brandWatermark?.minEdgeInset}px, max: ${lock.brandWatermark?.maxEdgeInset}px)`,
    `  - Inset Right: ${lock.brandWatermark?.insetRight}px`,
    `  - Width: ${lock.brandWatermark?.width}px`,
    `  - Opacity: ${lock.brandWatermark?.opacity} (min: ${lock.brandWatermark?.minOpacity}, max: ${lock.brandWatermark?.maxOpacity})`,
    `  - Animated: ${lock.brandWatermark?.animated ? 'true' : 'false'}`,
    `  - Safe Bottom Clearance: ${lock.brandWatermark?.safeBottom}px`,
    '',
    '---',
    '',
    '## 10. Typography Baseline',
    '',
    `Lock current ${lock.typography?.fontFamily} typography hierarchy:`,
    '',
    '### Title (\`TopicTitle\`)',
    `- Font Family: \`${lock.typography?.fontFamily}\``,
    `- Max Width: ${lock.typography?.title?.maxWidth}px`,
    `- Font Size: ${lock.typography?.title?.fontSize}px (min: ${lock.typography?.title?.minFontSize}px, max: ${lock.typography?.title?.maxFontSize}px)`,
    `- Line Height: ${lock.typography?.title?.lineHeight}`,
    `- Letter Spacing: ${lock.typography?.title?.letterSpacing}`,
    `- Font Weight: ${lock.typography?.title?.fontWeight}`,
    `- Max Lines: ${lock.typography?.title?.maxLines}`,
    `- Top Inset: ${lock.typography?.title?.top}px`,
    '',
    '### Subtitle (\`Subtitles\`)',
    `- Font Family: \`${lock.typography?.fontFamily}\``,
    `- Max Width: ${lock.typography?.subtitle?.maxWidth}px`,
    `- Font Size: ${lock.typography?.subtitle?.fontSize}px (min: ${lock.typography?.subtitle?.minFontSize}px, max: ${lock.typography?.subtitle?.maxFontSize}px)`,
    `- Line Height: ${lock.typography?.subtitle?.lineHeight}`,
    `- Bottom Placement: ${lock.typography?.subtitle?.bottomPlacement}`,
    `- Max Words Chunk: ${lock.typography?.subtitle?.maxWords}`,
    `- Font Weight: ${lock.typography?.subtitle?.fontWeight}`,
    '',
    '---',
    '',
    '## 11. Safe Zones (1080 × 1920)',
    '',
    `- Resolution: ${lock.safeZones?.resolution?.width} × ${lock.safeZones?.resolution?.height}`,
    `- Top Safe Zone (Brand & Title): y = ${lock.safeZones?.topZone?.[0]} .. ${lock.safeZones?.topZone?.[1]}px`,
    `- Center Artwork Zone: y = ${lock.safeZones?.centerArtworkZone?.[0]} .. ${lock.safeZones?.centerArtworkZone?.[1]}px`,
    `- Bottom Subtitle Zone: y = ${lock.safeZones?.bottomSubtitleZone?.[0]} .. ${lock.safeZones?.bottomSubtitleZone?.[1]}px`,
    '',
    '---',
    '',
    '## 12. Audio Contract & Single Dependency SSOT',
    '',
    `- **Dependency Contract Path:** \`${lock.audioContract?.dependencyContractPath}\``,
    `- **Default Background Music:** \`${lock.audioContract?.defaultBgMusic}\``,
    `- **SFX Policy:** \`${lock.audioContract?.sfxPolicy}\``,
    `- **Supported Audio Modes:** ${audioModes}`,
    '',
    '---',
    '',
    '## 13. Human QA Gate Contract',
    '',
    `- **Required:** ${lock.humanQa?.required ? 'Enforced' : 'Optional'}`,
    `- **Candidate Image Manifest Type:** \`${lock.humanQa?.imageManifestType}\``,
    `- **Approved Manifest Type:** \`${lock.humanQa?.approvedManifestType}\``,
    `- **Automatic Pass Prohibited:** ${lock.humanQa?.noAutomaticPass ? 'Enforced' : 'Disabled'}`,
    '',
    '---',
    '',
    '## 14. Pilot Verification Evidence',
    '',
    `- Verified Videos: ${verifiedVideos}`,
    `- Total Verified Shots: ${lock.evidence?.shotsCount}`,
    `- Overall Verification Status: \`${lock.evidence?.overallStatus}\``,
    ''
  ];

  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const isCheck = process.argv.includes('--check');
  const lockData = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
  const rendered = renderProductionLockMarkdown(lockData);

  if (isCheck) {
    if (!fs.existsSync(MD_PATH)) {
      console.error('Check failed: docs/HAY_DEP_PRODUCTION_LOCK.md does not exist.');
      process.exit(1);
    }
    const existing = fs.readFileSync(MD_PATH, 'utf8');
    if (existing.trim() !== rendered.trim()) {
      console.error('Check failed: docs/HAY_DEP_PRODUCTION_LOCK.md does not match JSON SSOT.');
      process.exit(1);
    }
    console.log('PASS: docs/HAY_DEP_PRODUCTION_LOCK.md is in sync with JSON SSOT.');
  } else {
    fs.writeFileSync(MD_PATH, rendered, 'utf8');
    console.log('Rendered docs/HAY_DEP_PRODUCTION_LOCK.md from JSON SSOT successfully.');
  }
}
